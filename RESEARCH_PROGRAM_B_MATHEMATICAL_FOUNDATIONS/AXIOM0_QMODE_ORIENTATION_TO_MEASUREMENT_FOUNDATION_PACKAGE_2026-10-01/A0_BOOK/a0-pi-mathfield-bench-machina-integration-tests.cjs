'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=(name)=>fs.readFileSync(path.join(__dirname,name),'utf8');
const exists=(name)=>fs.existsSync(path.join(__dirname,name));
let checks=0;
const ok=(value,message)=>{assert.ok(value,message);checks+=1};
const mathfield=read('A0_MATHEMATICAL_JOINTS.html');
const bench=read('A0_ORIENTATION_CONTROLLER_BENCH.html');
const machina=read('A0_MACHINA_COCKPIT.html');
const css=read('a0-pi-integration-dock.css');
const relation=require('./a0-machina-relation-chamber.js');
const receipt=JSON.parse(read('results/a0-platinum-iridium-pi-return-2026-11-11.json'));
for(const target of ['A0_PLATINUM_IRIDIUM_PI_LENS.html','A0_THREE_MATRIX_HOLONOMY_WORKBENCH.html','A0_MATHEMATICAL_JOINTS.html','A0_ORIENTATION_CONTROLLER_BENCH.html','A0_MACHINA_COCKPIT.html'])ok(exists(target),`target exists ${target}`);
ok((mathfield.match(/id="platinum-iridium-pi-holonomy-crosswalk"/g)||[]).length===1,'one Mathfield crosswalk');
for(const token of ['Dual Shell','Möbius','Klein','FOURIER','3 MATRIZEN','Penrose nur als Analogie'])ok(mathfield.includes(token),`Mathfield crosswalk ${token}`);
ok(mathfield.includes('A0_ORIENTATION_CONTROLLER_BENCH.html#piHolonomyBench')&&mathfield.includes('A0_MACHINA_COCKPIT.html#relationChamber'),'Mathfield routes Bench and Machina');
ok((bench.match(/id="piHolonomyBench"/g)||[]).length===1,'one Bench instrument entry');
ok(bench.includes('src="A0_THREE_MATRIX_HOLONOMY_WORKBENCH.html?embed=pi"'),'Bench embeds the canonical workbench');
for(const token of ['holonomy = 180°','2.828','2.309','det(A₃) = −1','det invariant'])ok(bench.includes(token),`Bench readout ${token}`);
ok(machina.includes('data-mrc-view="pi"')&&machina.includes('FULL PI LENS'),'Machina extends the existing chamber with one PI port');
ok(relation.VIEW_ROUTES.pi==='A0_PLATINUM_IRIDIUM_PI_LENS.html?embed=1'&&relation.VIEW_STATUS.pi.includes('3-MATRIX'),'PI projection route and status are explicit');
ok(css.includes('.pi-return-dock')&&css.includes('.pi-return-frame iframe'),'shared integration dock is styled');
ok(!mathfield.includes('A0_THREE_MATRIX_HOLONOMY_WORKBENCH.js')&&!bench.includes('A0_THREE_MATRIX_HOLONOMY_WORKBENCH.js'),'no copied engine script is introduced');
ok(receipt.integration_return&&receipt.integration_return.new_canonical_ids.length===0&&receipt.integration_return.relation_changes.length===0,'receipt preserves zero identity and relation changes');
ok(receipt.integration_return.permanent_a0_home==='MATHFIELD_CROSSWALK_BENCH_INSTRUMENT_MACHINA_PROJECTION','receipt records the owner-selected three-surface home');
console.log(`PASS a0-pi-mathfield-bench-machina-integration ${checks}/${checks}`);
