const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=__dirname;
const read=p=>fs.readFileSync(path.join(base,p),'utf8');
const cube=read('assets/game-of-worlds-play/ioi-world-cube/index.html');
const start=read('DRAFTS/A0_IOI_LEAF_FOLD_OPEN_BOOK_START_2026-11-02.html');
const pink=read('A0_PINK_DIAMOND_GRID_ATLAS.html');
const receipt=JSON.parse(read('results/a0-101-angle-hinge-dock-return-2026-11-06.json'));
const hinge=require('./a0-reciprocal-angle-hinge.js');
let pass=0;const ok=(v,m)=>{assert.ok(v,m);pass++;};
ok(cube.includes('../../../a0-reciprocal-angle-hinge.css')&&cube.includes('../../../a0-reciprocal-angle-hinge.js'),'world cube loads shared adapter assets');
ok(cube.includes('id="a0AngleHingeDock"')&&cube.includes('data-reciprocal-angle-hinge'),'world cube exposes mounted dock');
for(const ratio of ['1:2','2:3','1:1','3:2','2:1'])ok(cube.includes(`data-ratio="${ratio}"`),`dock contains ${ratio}`);
for(const action of ['swap','side','breath','reset'])ok(cube.includes(`data-action="${action}"`),`dock contains ${action}`);
ok(/kein Stop 13/i.test(cube),'dock explicitly rejects stop 13');
ok(start.includes('index.html#a0AngleHingeDock')&&start.includes('± HINGE'),'101/A0 start routes through dock');
ok(pink.includes('index.html#a0AngleHingeDock')&&pink.includes('Angle Hinge Dock'),'Pink Diamond exposes subordinate route');
const tour=(cube.match(/const tourSteps=\[(.*?)\];\s*let tourIndex/s)||[])[1]||'';
ok((tour.match(/title:/g)||[]).length===12,'frozen tour still has exactly 12 steps');
ok(cube.includes('00 / 12'),'visible frozen tour count remains 12');
const s=hinge.signedState(1,2,3),r=hinge.cycle(s);
ok(r.side===s.side&&r.p===s.p&&r.q===s.q,'signed reciprocal state returns after two flips');
ok(Object.values(receipt.effects).every(v=>v===0||v===false),'receipt declares zero semantic or publication effects');
ok(receipt.tour_effect.frozen_steps_after===12&&receipt.tour_effect.is_stop_13===false,'receipt preserves tour freeze');
for(const text of [cube,start,pink])ok(!/yin|yang/i.test(text),'target surface contains no Yin-Yang framing');
console.log(JSON.stringify({suite:'a0-101-angle-hinge-dock',pass,status:'PASS'},null,2));
