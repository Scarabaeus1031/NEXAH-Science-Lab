const fs = require('node:fs');
const path = require('node:path');

const receipt = require('./results/a0-primecube-sz-khipu-paper-return-2026-11-22.json');
const deskReturn = 'A0_RESEARCH_DESK.html#primecube-sz-khipu-paper-return-20261122';
const figureSource = '[Open figure and five-stage receipt](A0_BOOK/A0_PRIMECUBE_GAP_FOLD_LAB.html#primecube-reviewer-packet)';
const figureLink = '<a href="../A0_PRIMECUBE_GAP_FOLD_LAB.html#primecube-reviewer-packet">Open figure and five-stage receipt</a>';

function escapeHtml(text) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function renderNote(paper) {
  const [source, anchor] = receipt.paper_routing[`paper_${paper}`].split('#');
  const manuscript = fs.readFileSync(path.join(__dirname, source), 'utf8');
  const marker = `<a id="${anchor}"></a>`;
  const index = manuscript.indexOf(marker);
  if (index === -1) throw new Error(`Missing manuscript anchor: ${source}#${anchor}`);

  const [heading, ...lines] = manuscript.slice(index + marker.length).trimStart().split(/\r?\n/);
  if (!heading.startsWith('### ')) throw new Error(`Missing note heading: ${source}#${anchor}`);
  const nextHeading = lines.findIndex(line => /^#{1,6} /.test(line));
  const note = (nextHeading === -1 ? lines : lines.slice(0, nextHeading)).join('\n').trim();
  return `    <section id="${anchor}" aria-labelledby="${anchor}-title" lang="en">
      <h2 id="${anchor}-title">Paper ${paper.toUpperCase()} · ${escapeHtml(heading.slice(4))}</h2>
      <p class="source">${escapeHtml(path.basename(source))}</p>
      <pre>${escapeHtml(note).replace(figureSource, figureLink)}</pre>
    </section>`;
}

const html = `<!doctype html>
<html lang="de">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>PrimeCube · Manuskriptabschnitte</title>
  <style>
    :root{color-scheme:dark;background:#101922;color:#e8eef3;font:1rem/1.55 system-ui,sans-serif}
    body{max-width:62rem;margin:auto;padding:clamp(16px,4vw,40px)}
    a{color:#89deed;text-underline-offset:.2em}
    section{padding:1rem;margin:1.5rem 0;scroll-margin-top:1rem;border:1px solid #39505d;border-radius:8px;background:#07141d}
    section:target{outline:2px solid #89deed;outline-offset:3px}
    h2{margin:0}
    .source{color:#a9bbc8;overflow-wrap:anywhere}
    pre{white-space:pre-wrap;overflow-wrap:anywhere;font:.92rem/1.6 ui-monospace,monospace;margin-bottom:0}
  </style>
</head>
<body>
  <!-- Generated by build-a0-primecube-paper-notes.cjs. -->
  <header>
    <a href="../${deskReturn}">← Zum Science Desk</a>
    <h1>PrimeCube · Manuskriptabschnitte</h1>
  </header>
  <main>
${['c', 'e', 'f'].map(renderNote).join('\n')}
  </main>
</body>
</html>
`;

const output = path.join(__dirname, 'DRAFTS', 'A0_PRIMECUBE_PAPER_NOTES.html');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== html) {
    throw new Error('Run node build-a0-primecube-paper-notes.cjs to refresh the notes.');
  }
} else {
  fs.writeFileSync(output, html);
}
