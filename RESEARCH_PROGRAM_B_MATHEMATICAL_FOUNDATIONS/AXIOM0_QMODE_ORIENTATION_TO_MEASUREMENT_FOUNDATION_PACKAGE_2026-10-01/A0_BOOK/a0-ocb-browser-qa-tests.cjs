'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),Q=require('./a0-ocb-browser-qa.js');
let checks=0;
const ok=(v,m)=>{assert.ok(v,m);checks++};
const html=fs.readFileSync('./A0_ORIENTATION_CONTROLLER_BENCH.html','utf8');
const css=[fs.readFileSync('./a0-aperture-stack-calibration.css','utf8'),fs.readFileSync('./a0-aperture-measurement.css','utf8')].join('\n');
const audit=Q.staticAudit(html,css);
ok(audit.status==='PASS','static QA pass');
audit.checks.forEach(item=>ok(item.pass,item.name));
ok(Q.VIEWPORTS.length===3,'three viewport contracts');
ok(Q.VIEWPORTS.some(v=>v.id==='wide'&&v.width===1440),'wide contract');
ok(Q.VIEWPORTS.some(v=>v.id==='tablet'&&v.width===820),'tablet contract');
ok(Q.VIEWPORTS.some(v=>v.id==='phone'&&v.width===390),'phone contract');
const required=['apertureMeasurement','m3Play','m3Step','m3Reset','m3Export','apertureStackCalibration','apStackPlay','apStackStep','apStackReset','apStackExport','apStackMode','apStackWindow'];
const nodes=Object.fromEntries(required.map(id=>[id,{id,getAttribute:key=>id==='apertureStackCalibration'&&key==='aria-labelledby'?'apStackTitle':null}]));
nodes.apStackStatus={getAttribute:key=>key==='aria-live'?'polite':null};
const doc={hidden:false,getElementById:id=>nodes[id]},win={innerWidth:390,innerHeight:844,matchMedia(){return{matches:false}}};
const runtime=Q.runtimeAudit(doc,win);
ok(runtime.status==='PASS','runtime QA pass');
ok(runtime.viewport.class==='phone','phone classified');
runtime.results.forEach(item=>ok(item.pass,item.name));
console.log(JSON.stringify({status:'PASS',checks,viewports:Q.VIEWPORTS,scope:'OCB-GAP-09 automated contract; manual multi-viewport pixel acceptance remains open'}));
