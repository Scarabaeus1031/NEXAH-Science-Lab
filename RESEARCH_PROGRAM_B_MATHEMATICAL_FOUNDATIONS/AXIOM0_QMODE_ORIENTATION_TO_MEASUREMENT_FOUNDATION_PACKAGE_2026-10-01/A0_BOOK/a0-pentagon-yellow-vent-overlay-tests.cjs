ok(modelSource,'ventOverlayModel source is extractable');
const context={Math,Number};
vm.runInNewContext('const rad=d=>d*Math.PI/180;'+modelSource[0].replace(/\nfunction renderVentOverlay$/,'')+';globalThis.model=ventOverlayModel;',context);
const model=context.model(137.6,29);
