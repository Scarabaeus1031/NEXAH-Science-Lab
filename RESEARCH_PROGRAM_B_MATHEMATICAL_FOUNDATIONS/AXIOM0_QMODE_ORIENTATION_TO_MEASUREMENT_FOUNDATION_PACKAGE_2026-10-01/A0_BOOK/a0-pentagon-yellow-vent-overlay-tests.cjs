const ok=(value,label)=>{assert.ok(value,label);checks+=1};
for(const marker of ['id="yellowVentOverlay"','id="ventOverlayScene"','id="ventAtom"','id="ventDrops"','id="ventBench"','id="ventReturn"','id="ventAngle"'])ok(html.includes(marker),`contains ${marker}`);
