ok(/ventOverlayState\.atom=false;ventOverlayState\.drops=false;ventOverlayState\.bench=false/.test(html),'RETURN disables all three view layers');
ok(/globalThis\.PentagonLab=\{[^}]*ventOverlayModel,renderVentOverlay/.test(html),'overlay helpers remain inspectable through PentagonLab');
console.log(`PASS · ${checks} Yellow Vent overlay checks · EXISTING LANTERN / VIEW ONLY`);
