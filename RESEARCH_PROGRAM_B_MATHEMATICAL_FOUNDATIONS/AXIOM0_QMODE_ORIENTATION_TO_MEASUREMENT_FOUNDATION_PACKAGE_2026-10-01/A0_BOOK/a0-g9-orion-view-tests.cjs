const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const G9=require('./assets/a0-field-notes/g9-orion-view.js');
let checks=0;
const ok=(value,label)=>{assert.ok(value,label);checks++;};
const modelLink=path.join(__dirname,'assets/3d/NEXAH_NTO_11357_ORION_ASTROLABE_v6_ROOT_SHRINK_TRAMPOLINE.glb');
const source=fs.realpathSync(modelLink),buffer=fs.readFileSync(source),jsonLength=buffer.readUInt32LE(12);
const gltf=JSON.parse(buffer.toString('utf8',20,20+jsonLength).replace(/\u0000+$/,''));
const names=(gltf.animations||[]).map(animation=>animation.name);
ok(fs.lstatSync(modelLink).isSymbolicLink(),'A0 binds the canonical archived GLB without a binary copy');
ok(source.endsWith('/SCIENCE_LAB/CASE_STUDIES/NEXAH_NTO_11357_ORION_ASTROLABEs/NEXAH_NTO_11357_ORION_ASTROLABE_v6_ROOT_SHRINK_TRAMPOLINE.glb'),'symlink resolves to the archived case-study source');
ok(gltf.asset?.extras?.nexah_motion_v6?.duration_seconds===18,'source declares the 18 second v6 motion');
ok(gltf.asset?.extras?.nexah_motion_v6?.sequence?.join('/')==='SHRINK/BEND/CROSS/INVERT/RELEASE','source motion grammar remains exact');
ok(names.includes(G9.CLIPS.root)&&names.includes(G9.CLIPS.museum),'both declared animation clips exist in the source GLB');
ok(G9.SIDES.g9.label.includes('HELLBLAU')&&G9.SIDES.counter.label.includes('GELB / ROT / WEISS'),'G9 and counter-side display codes are exported');
const html=fs.readFileSync(path.join(__dirname,'assets/a0-field-notes/index.html'),'utf8');
ok(html.includes('id="g9-orion-rotation"')&&html.includes('g9-orion-view.js?v=')&&html.includes('g9-orion-view.css?v='),'reader binds the G9 viewer and versioned assets');
ok(html.includes('ROOT_SHRINK_TRAMPOLINE_BREATH')&&html.includes('NEXAH_MUSEUM_CYCLE_ORIGINAL_INVERSE_SILO'),'reader exposes both source animation clips');
ok(html.includes('G9_RETURN_WITH_MEMORY')&&html.includes('keine neue G9-Identität'),'reader keeps the G9 semantic boundary visible');
console.log(`PASS A0 G9 Orion View · ${checks}/${checks}`);
