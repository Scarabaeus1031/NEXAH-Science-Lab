function escapeHtml(text) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
    .replace(/[ \t]+$/gm, whitespace => whitespace.replaceAll(' ', '&#32;').replaceAll('\t', '&#9;'));
}

function renderRecord({ id, title, source, anchors = [] }) {
  let contents = escapeHtml(fs.readFileSync(path.join(__dirname, source), 'utf8'));
  for (const anchor of anchors) {
    const marker = escapeHtml(`<a id="${anchor}"></a>`);
    if (!contents.includes(marker)) throw new Error(`Missing source anchor: ${anchor}`);
    contents = contents.replace(marker, `<span id="${anchor}" class="source-anchor"></span>`);
  }
  return `    <section id="${id}" aria-labelledby="${id}-title">
      <h2 id="${id}-title">${escapeHtml(title)}</h2>
      <p class="filename">${escapeHtml(path.basename(source))}</p>
      <pre>${contents}</pre>
    </section>`;
}

