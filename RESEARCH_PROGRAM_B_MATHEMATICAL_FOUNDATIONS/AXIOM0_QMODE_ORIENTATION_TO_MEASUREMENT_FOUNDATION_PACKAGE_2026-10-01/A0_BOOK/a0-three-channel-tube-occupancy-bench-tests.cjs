'use strict';
const assert=require('node:assert/strict');
const bench=require('./a0-three-channel-tube-occupancy-bench.js');
let checks=0;const same=(a,b,m)=>{assert.deepEqual(a,b,m);checks+=1;};const ok=(v,m)=>{assert.ok(v,m);checks+=1;};
same(bench.IDENTITY,'NEXAH_A0_ORIENTATION_CONTROLLER_BENCH','reuses Bench identity');
same(bench.ILAU_ID,'SG:LENS:ILAU_ORIENTATION','reuses ILAU lens');
same(bench.PORTS.length,3,'three ports');
same(bench.PORTS.map(p=>p.ordinal),[1,2,3],'ordinals');
same(bench.PORTS.map(p=>p.id),['chemistry','life','physics'],'source ids');
same(new Set(bench.PORTS.map(p=>p.color)).size,3,'colors remain distinct');
same(bench.BINS.length,8,'eight bins');
same(new Set(bench.BINS).size,8,'bins unique');
const state=bench.createState();
ok(bench.PORTS.every(p=>state.occupancy[p.id].complete),'complete occupancy');
const view=bench.derive(state);
same(view.status,'EXACT_VIEW','exact default');
same(view.contributions.length,3,'three contributions');
same(view.feedback,false,'no feedback');
same(view.source_mutation,false,'no source mutation');
ok(Number.isFinite(view.witness.re)&&Number.isFinite(view.witness.im),'finite witness');
const missing=bench.createState({missing_port:'life'});
same(bench.derive(missing).status,'HOLD_MISSING_SOURCE','missing holds');
const incomplete=bench.createState();incomplete.occupancy.physics.complete=false;
same(bench.derive(incomplete).status,'HOLD_INCOMPLETE_OCCUPANCY','incomplete holds');
const captured=bench.capture(state);
same(captured.status,'CAPTURED','capture exact');
same(bench.validateCapture(captured),'EXACT_RETURN','capture validates');
const altered=JSON.parse(JSON.stringify(captured));altered.witness.re=9;
same(bench.validateCapture(altered),'HOLD_TAMPERED_FINGERPRINT','tamper holds');
const replayed=bench.replay(captured);
same(replayed.status,'REPLAYED','replay status');
same(replayed.source_mutation,false,'replay no source mutation');
same(replayed.feedback,false,'replay no feedback');
same(replayed.state.occupancy,state.occupancy,'occupancy restored');
same(replayed.witness,captured.witness,'witness restored');
same(replayed.fingerprint,captured.fingerprint,'fingerprint restored');
for(const bin of bench.BINS){const vector=bench.vectorFor(bin);ok(Number.isFinite(vector.re)&&Number.isFinite(vector.im),`${bin} vector`);}
const battery=bench.runChecks();
same(battery.status,'PASS','battery pass');
same(battery.passed,6,'six passed groups');
same(battery.total,6,'six groups');
same(battery.checks.map(c=>c.n),[1,2,3,4,5,6],'ordered groups');
same(battery.new_ids,0,'no new ids');
same(battery.new_relations,0,'no new relations');
console.log(`PASS ${checks}/${checks} — interactive three-channel Tube Occupancy Bench`);
