const assert=require('node:assert/strict');
const M=require('./a0-spectral-shadow-return-machine.js');
let checks=0;const ok=(v,m)=>{assert.ok(v,m);checks++};
const near=(a,b)=>ok(Math.abs(a-b)<1e-12,`${a} != ${b}`);
const a=M.state(0,0,'forward','white'),b=M.state(1,90,'forward','red'),mid=M.state(.5,45,'forward','cyan');
near(a.ringSpacing,12);near(b.ringSpacing,12);ok(mid.ringSpacing<5,'rings approach inner at midpoint');
ok(a.returnClosed&&b.returnClosed,'endpoints close');ok(!mid.returnClosed,'middle remains open');
ok(M.state(.2,0,'return','white').route===.8,'return reverses reading direction');
ok(M.SHADOWS.cyan.blocked.join('')==='R','cyan is residual G+B');
ok(M.SHADOWS.magenta.blocked.join('')==='G','magenta is residual R+B');
ok(M.SHADOWS.yellow.blocked.join('')==='B','yellow is residual R+G');
ok(M.SHADOWS.red.blocked.join('')==='GB','red residual leaves only R');
ok(M.state(.5,140,'forward','white').axis===90,'axis tilt is bounded to 90 degrees');
ok(M.state(.5,-140,'forward','white',140).axis===-90,'signed axis tilt is bounded to minus 90 degrees');
ok(M.state(.5,0,'forward','white',140).counterAxis===90,'counter tilt is bounded to 90 degrees');
ok(M.record(mid).nautilusRole==='HISTORICAL_VISUAL_MORPHOLOGY_ONLY','nautilus is not promoted');
const con=M.sequenceProjection('CON-6'),still=M.sequenceProjection('STILL'),dao=M.sequenceProjection('DAO-6');
ok(con.primaryAngle===-75&&con.counterAngle===75,'CON begins with paired counter tilt');
ok(still.primaryAngle===0&&still.counterAngle===0&&still.plusOne,'STILL fixes the paired carrier and exposes +1');
ok(dao.primaryAngle===75&&dao.counterAngle===-75,'DAO returns through the opposed view');
ok(M.sequenceProjection('UNKNOWN')===null,'unknown sequence state is not projected');
const zw=M.zetaRotate(.5,14.134725);
near(zw.re,-14.134725);near(zw.im,0);near(zw.reOfIS,-14.134725);
ok(M.zetaRotate(.875,10).im===.375,'centered rotation preserves sigma displacement');
ok(M.record(mid,still).sequence.sourceModel==='NEXAH:CON_DAO_BREATH:V1','sequence record reuses the source model');
ok(M.record(mid,still).zetaView.claim==='EXACT_AFFINE_COORDINATE_VIEW_ONLY','zeta map remains a coordinate view');
console.log(`${checks}/${checks} PASS · spectral-shadow-return-machine`);
