const assert=require('node:assert/strict');
const fold=require('./assets/a0-axis08-fold-return-sequencer-v1.js');
const color=require('./assets/a0-newton-goethe-observer-lens-v1.js');
const lensRecord=require('./assets/a0-newton-goethe-observer-lens-v1.json');
const values=[-2.4,-1.2,-.7,-.25,.45,.9,1.7,2.6];
assert.equal(fold.PHASES.length,8);
assert.equal(fold.phase(4).id,'fold');
const direct=fold.fold(values,3,false);
assert.deepEqual(direct.pairDisplay,[4,5]);
assert.equal(direct.quotient.length,7);
assert.ok(direct.error<1e-12);
const flipped=fold.fold(values,3,true);
assert.ok(flipped.error<1e-12);
assert.equal(flipped.residual,-direct.residual);
assert.throws(()=>fold.fold(values,7),/pairStart/);
assert.equal(color.BANDS.length,7);
assert.equal(color.relation(42,.18).angle,42);
assert.equal(color.relation(120,.18).angle,90);
const sample=color.sample(.2,-.4,42,.18);
assert.ok(Number.isFinite(sample.residual));
assert.ok(sample.residual>=0);
assert.deepEqual(lensRecord.display_modes.map(({id})=>id),['wide_three_window','vertical_section']);
assert.equal(lensRecord.new_navigator_identity,false);
assert.equal(lensRecord.new_graph_relation,false);
console.log(JSON.stringify({status:'PASS',assertions:16,phases:fold.PHASES.length,returnError:direct.error,bands:color.BANDS.length,displayModes:lensRecord.display_modes.map(({id})=>id),boundary:'AXIS08 exact representation return; Newton/Goethe remains a separated observer comparison'},null,2));
