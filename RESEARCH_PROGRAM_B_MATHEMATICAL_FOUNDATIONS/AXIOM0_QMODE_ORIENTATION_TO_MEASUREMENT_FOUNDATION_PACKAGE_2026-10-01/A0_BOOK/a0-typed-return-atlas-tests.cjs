"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const api = require("./a0-typed-return-atlas.js");
const base = __dirname;
const html = fs.readFileSync(path.join(base, "A0_WERKBANK.html"), "utf8");
const css = fs.readFileSync(path.join(base, "a0-bench-navigation.css"), "utf8");
const contract = JSON.parse(fs.readFileSync(path.join(base, "results/a0-typed-return-contract-v1.json"), "utf8"));
const receipt = JSON.parse(fs.readFileSync(path.join(base, "results/a0-typed-return-atlas-return-2026-10-30.json"), "utf8"));
let checks = 0;
const check = (v, m) => { assert.ok(v, m); checks += 1; };
const verified = api.verify();
check(verified.pass && verified.records === 112, "112 cross-instrument records pass");
check(verified.fib7.length === 16, "Pisano period mod 7 is 16");
check(verified.fib7.unique.join(",") === "0,1,2,3,4,5,6", "Fibonacci mod 7 covers every residue");
check(new Set(verified.fib7.period).size < 16, "Fibonacci period is not a permutation");
check(api.diagonalPrimeLift(1).target.join(",") === "2,2", "diagonal one lifts to prime pair two-two");
check(api.diagonalPrimeLift(2).target.join(",") === "3,3", "diagonal two lifts to prime pair three-three");
check(api.diagonalPrimeLift(0) === null, "zero has no prime-index lift");
check(api.signedDodeca(1).period === 12 && api.signedDodeca(1).exactReturn, "+1/12 returns after twelve steps");
check(api.signedDodeca(-1).period === 12 && api.signedDodeca(-1).exactReturn, "-1/12 returns after twelve steps");
check(api.signedDodeca(2).period === 6 && api.signedDodeca(2).exactReturn, "+2/12 returns after six steps");
check(api.signedDodeca(-2).period === 6 && api.signedDodeca(-2).exactReturn, "-2/12 returns after six steps");
check(api.lAffineControl().exact && api.lAffineControl().inverse === 44, "44 plus six reaches Roman L and returns exactly");
check(!api.lAffineControl().phiBinding && api.FQ_OPEN_PORTS.every(x => x.state !== "BOUND"), "phi and colour ports remain unbound");
check(["ZE|TA", "Hz", "mph", "¥"].every(port => api.FQ_OPEN_PORTS.some(x => x.port === port)), "token, frequency, speed and glyph ports stay visibly open");
const rath = api.rathNeighborLadder();
check(rath.foldNeighbor.exact && rath.foldNeighbor.angleNamespaceSeparate, "44 to 45 is exact while angle namespace stays separate");
check(rath.shell.value === 49 && rath.shell.factorization === "7²" && rath.shell.totient === 42, "RATH 49 shell reuses exact seven-square totient profile");
check(rath.rathGate.exact && rath.rathGate.value === 51 && rath.rathGate.factorization === "3·17", "44 plus seven reaches composite RATH gate 51");
check(rath.balance.exact && rath.balance.sum === 100, "49 and 51 balance to one hundred");
check(rath.primeAddresses.seventySeven === "p4·p5" && rath.primeAddresses.p7 === 17, "77 uses p4 times p5 while 17 is separate p7 address");
check(api.CONTRACT_FIELDS.length === 11, "eleven required fields");
check(contract.requiredFields.join("|") === api.CONTRACT_FIELDS.join("|"), "JSON and module contract fields agree");
check(api.STAGES.length === 7, "seven typed stages");
check(api.OPEN_MARKERS.length === 7, "seven typed open markers");
for (const direction of ["+1", "−1", "+2", "−2"]) {
  check(Array.from({ length: 28 }, (_, n) => api.makeRecord(n, direction)).every(r => r.return_witness.exact), `${direction} exact return`);
}
check(Array.from({ length: 28 }, (_, n) => api.qrt11(n).return === n).every(Boolean), "QRT11 quotient and residue reconstruct every address");
check(Array.from({ length: 28 }, (_, n) => api.counterweight(n).oneBasedSum === 29).every(Boolean), "counterweight comparator sums to 29");
check(api.makeRecord(6, "+1").seam.outgoing && api.makeRecord(13, "+1").seam.outgoing && api.makeRecord(20, "+1").seam.outgoing, "three seams declared");
check(api.makeRecord(0, "+1").negative_control.halfTwistOneCircuit === "EXPECTED_FAIL", "negative control visible");
check(api.routeSvg(api.makeRecord(0, "+1")).includes("PASS · EXACT RETURN"), "route renderer shows pass");
check(api.fibonacciSvg().includes("PERIOD 16"), "Fibonacci renderer shows period");
check(api.fibonacciSvg().includes("Δ1→Δ2 · Δ2→Δ3"), "Fibonacci renderer separates prime-index lift");
check(api.fqComparatorSvg().includes("PERIOD 12") && api.fqComparatorSvg().includes("49=7²") && api.fqComparatorSvg().includes("77=p₄·p₅") && api.fqComparatorSvg().includes("ZE|TA · Hz · mph · ¥"), "FQ comparator renders dodeca, RATH rail and open unit ports");
check(api.ledgerHtml(api.makeRecord(0, "+1")).includes("return_witness"), "ledger renderer contains witness");
check(api.markersHtml().includes("PANTONE / COLOUR"), "marker catalog rendered");
check(html.includes('id="typedReturnAtlas"') && html.includes('data-tra-view="fibonacci"') && html.includes('data-tra-view="fq"'), "workbench atlas mounted");
check(html.includes("a0-typed-return-atlas.js?rev=typed-return-r1-20261030"), "versioned atlas loaded");
check(css.includes(".tra-atlas") && css.includes(".tra-fib-path"), "atlas styling present");
check(receipt.nsnReturn.newCanonicalIds === 0 && receipt.nsnReturn.relationChanges === 0, "NSN effect explicitly zero");
check(receipt.scienceDesk.studyActivation === 0 && receipt.publication === false, "no activation or publication");
check(receipt.acceptance.startsWith("CANDIDATE_ONLY"), "acceptance remains candidate-only");
console.log(`PASS a0-typed-return-atlas ${checks}/${checks} · module ${verified.passed}/${verified.total}`);
