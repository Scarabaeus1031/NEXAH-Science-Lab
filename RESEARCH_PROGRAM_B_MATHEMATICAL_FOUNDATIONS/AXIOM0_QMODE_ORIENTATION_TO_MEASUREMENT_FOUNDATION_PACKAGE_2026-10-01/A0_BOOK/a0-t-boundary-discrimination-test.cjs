const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const prereg=JSON.parse(fs.readFileSync(path.join(root,'results/a0-t-boundary-discrimination-preregistration-2026-11-01.json'),'utf8'));
const result=JSON.parse(fs.readFileSync(path.join(root,'results/a0-t-boundary-discrimination-return-2026-11-01.json'),'utf8'));
const T=([a,b])=>[b,a];
const h=([a,b])=>Math.sign(b-a);
const key=(pair)=>pair.join('|');
const slices=[prereg.object.main_slice,...prereg.controls.even_sum_slices,...prereg.controls.odd_sum_slices];
const states=slices.flatMap((slice)=>slice.states);
const uniqueStates=[...new Map(states.map((state)=>[key(state),state])).values()];
assert.equal(uniqueStates.length,13);
assert(uniqueStates.every((state)=>key(T(T(state)))===key(state)));
assert(uniqueStates.every((state)=>h(T(state))===-h(state)));
assert(uniqueStates.every((state)=>(h(state)===0)===(state[0]===state[1])));
const main=prereg.object.main_slice.states;
assert.deepEqual(main.filter((state)=>key(T(state))===key(state)),[[8,8]]);
assert.deepEqual(T([7,9]),[9,7]);
assert.equal(79+97,2*88);
assert.equal(result.verdict,'PASS_LOCAL_HANDLE_NEGATIVE_GLOBAL_UNIQUENESS');
assert.equal(result.test_results.filter((test)=>test.pass).length,5);
assert.deepEqual(result.bindings,{dao:'NONE',god_dog:'NONE',dg_gd:'NONE'});
