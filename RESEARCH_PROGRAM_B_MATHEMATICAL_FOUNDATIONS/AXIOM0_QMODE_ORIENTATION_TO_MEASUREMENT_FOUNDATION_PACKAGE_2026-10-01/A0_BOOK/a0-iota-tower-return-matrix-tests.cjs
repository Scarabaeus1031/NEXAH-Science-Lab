const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const matrix=require('./a0-iota-tower-return-matrix.js');
const iota=require('./a0-iota-2-3-bridge-probe.js');
const tower=require('./a0-tower-shell-return.js');

let checks=0;const check=(value,message)=>{assert.ok(value,message);checks+=1};
const pin={schema:'nexah.a0.tl-final-pin-view/1',identity:matrix.IDENTITY,state:{scanner:{screenRead:'OCCUPIED'}},pin:{decision:'PINNED_2_TO_1',address:'q01'}};
const dg={schema:'nexah.a0.dg-sampling-loop-record/1',identity:matrix.IDENTITY,current:{stage:'RETURN',sample:'15/18',wheelDeg:280,samples:18,bands:5}};
const witness={status:'WITNESS_HELD',address:'q01',basis:{samples:18,bands:5}};
const receipt=tower.closeReturn(pin,dg,witness);
const closed=tower.buildRecord(pin,dg,witness,receipt);
const open=matrix.projectOpenTower(closed);
const bridge=iota.viewRecord({...iota.createViewState(),tick:24});
const isolation={iotaResetPreservesTower:true,towerResetPreservesIota:true,towerRunPreservesIota:true,iotaReplayPreservesTower:true};
const ledger=matrix.buildLedger({bridgeRecord:bridge,openTowerRecord:open,closedTowerRecord:closed,isolation});

check(matrix.VERSION==='1.0.0','version');
check(matrix.IDENTITY==='NEXAH_A0_ORIENTATION_CONTROLLER_BENCH','identity');
check(open.schema===closed.schema,'projection schema');
check(open.identity===closed.identity,'projection identity');
check(open.state.closed===false,'projection opens state');
check(open.receipt===null,'projection removes receipt');
check(closed.state.closed===true,'source remains closed');
check(matrix.fingerprintBridge(bridge).includes('24'),'bridge fingerprint');
check(matrix.fingerprintTower(closed).includes('CLOSED_TYPED_VIEW_RETURN'),'tower fingerprint');
check(ledger.schema==='nexah.a0.iota-tower-return-matrix/1','ledger schema');
check(ledger.identity===matrix.IDENTITY,'ledger identity');
check(ledger.classification==='METHOD_RELEVANT_ENGINEERING_OBSERVATION','classification');
check(ledger.status==='PASS','ledger pass');
check(ledger.matrix.pass===true,'matrix pass');
check(ledger.matrix.rows.length===4,'four rows');
check(ledger.matrix.rows.map(row=>row.code).join(',')==='00,10,01,11','row order');
check(ledger.matrix.rows[0].observed==='HOLD','00 hold');
check(ledger.matrix.rows[1].observed==='HOLD','10 hold');
check(ledger.matrix.rows[2].observed==='HOLD','01 hold');
check(ledger.matrix.rows[3].observed==='COUPLED_VIEW_RETURN','11 closes');
check(ledger.matrix.rows.every(row=>row.pass),'all rows expected');
check(ledger.matrix.rows.filter(row=>row.observed==='COUPLED_VIEW_RETURN').length===1,'only one closure');
check(ledger.isolationPass===true,'isolation pass');
check(Object.values(ledger.isolation).every(Boolean),'four isolation checks');
check(ledger.provenance.bridge.schema==='nexah.a0.iota-2-3-bridge-view/1','bridge provenance schema');
check(ledger.provenance.bridge.tick===24,'bridge provenance tick');
check(ledger.provenance.bridge.periods.am===8,'AM provenance');
check(ledger.provenance.bridge.periods.pm===12,'PM provenance');
check(ledger.provenance.bridge.receipt==='BRIDGE_RETURN_READY','bridge receipt');
check(ledger.provenance.tower.schema==='nexah.a0.tower-shell-return-view/1','tower provenance schema');
check(ledger.provenance.tower.address==='q01','tower address');
check(ledger.provenance.tower.returnSample==='15/18','tower sample');
check(ledger.provenance.tower.basis.samples===18,'tower samples basis');
check(ledger.provenance.tower.basis.bands===5,'tower bands basis');
check(ledger.provenance.tower.receipt==='CLOSED_TYPED_VIEW_RETURN','tower receipt');
check(ledger.coupled.status==='COUPLED_VIEW_RETURN','coupled status');
check(ledger.coupled.coupling.sharedClock===false,'no shared clock');
check(ledger.coupled.coupling.changesDgClock===false,'no DG clock change');
check(ledger.coupled.coupling.mapsQToN===false,'no q to N map');
check(ledger.authority.researchRun===false,'no research run');
check(ledger.authority.scientificEvidence===false,'no science evidence');
check(ledger.authority.newIdentity===false,'no new identity');
check(ledger.authority.newRelation===false,'no new relation');
check(ledger.authority.newCarrier===false,'no new carrier');
check(ledger.authority.newOperator===false,'no new operator');
check(ledger.authority.claimPromotion===false,'no claim promotion');
check(ledger.boundary.includes('separate provenance'),'separate provenance boundary');
check(ledger.boundary.includes('no shared clock'),'shared clock boundary');
const held=matrix.buildLedger({bridgeRecord:iota.viewRecord(iota.createViewState()),openTowerRecord:open,closedTowerRecord:closed,isolation});
check(held.status==='HOLD','early bridge holds');
const unisolated=matrix.buildLedger({bridgeRecord:bridge,openTowerRecord:open,closedTowerRecord:closed,isolation:{}});
check(unisolated.status==='HOLD','unverified isolation holds');
const base=__dirname,html=fs.readFileSync(path.join(base,'A0_ORIENTATION_CONTROLLER_BENCH.html'),'utf8'),css=fs.readFileSync(path.join(base,'a0-iota-tower-return-matrix.css'),'utf8');
check(html.includes('id="iotaTowerReturnMatrix"'),'html anchor');
check(html.includes('a0-iota-tower-return-matrix.css'),'css linked');
check(html.includes('a0-iota-tower-return-matrix.js'),'script linked');
check(html.includes('id="iotaTowerMatrixRun"'),'run button');
check(html.includes('NO SHARED CLOCK'),'visible boundary');
check(css.includes('.itrm-grid'),'matrix CSS');
console.log(`A0 IOTA/Tower return matrix: ${checks} checks passed.`);
