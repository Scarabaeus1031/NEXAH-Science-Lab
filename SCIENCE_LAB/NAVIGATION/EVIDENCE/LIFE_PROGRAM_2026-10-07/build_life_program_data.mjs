#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, "../../../CASE_STUDIES/NEXAH_LIFE_PROGRAM_CONSOLIDATION_2026-10-07/LIFE_PROGRAM_REGISTER.json");
const target = path.resolve(here, "../../APP/life-program.internal.js");
const register = JSON.parse(fs.readFileSync(source, "utf8"));
const projection = {
  schema: "nexah.navigator.life-program-lens",
  version: "1.0.0",
  date: register.date,
  status: "INTERNAL_READ_ONLY_PROGRAM_LENS",
  counts: register.counts,
  program_lines: register.program_lines,
  records: register.records,
  controlling_record: "SCIENCE_LAB/CASE_STUDIES/NEXAH_LIFE_PROGRAM_CONSOLIDATION_2026-10-07/LIFE_PROGRAM_REGISTER.json",
  readme: "SCIENCE_LAB/CASE_STUDIES/NEXAH_LIFE_PROGRAM_CONSOLIDATION_2026-10-07/00_README.md",
  audit: "SCIENCE_LAB/CASE_STUDIES/NEXAH_LIFE_PROGRAM_CONSOLIDATION_2026-10-07/results/LIFE_PROGRAM_AUDIT.json",
  global_claim_ceiling: register.global_claim_ceiling
};
const serialized = JSON.stringify(projection).replaceAll("</script", "<\\/script");
const output = `/* Generated by build_life_program_data.mjs from the authoritative LIFE program register. */\nwindow.NEXAH_LIFE_PROGRAM = ${serialized};\n`;

fs.writeFileSync(target, output);
console.log(JSON.stringify({
  status: "PASS",
  source: path.relative(here, source),
  target: path.relative(here, target),
  records: projection.records.length,
  dedicated_html_apps: projection.counts.dedicated_html_apps,
  html_surfaces_total: projection.counts.html_surfaces_total,
  bytes: Buffer.byteLength(output)
}, null, 2));
