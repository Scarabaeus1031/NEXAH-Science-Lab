#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, "OBSERVATORY_NAVIGATOR_BINDING_V1_2026-10-07.json");
const target = path.resolve(here, "../../APP/observatory.internal.js");
const binding = JSON.parse(fs.readFileSync(source, "utf8"));
const serialized = JSON.stringify(binding).replaceAll("</script", "<\\/script");
const output = `/* Generated by build_observatory_data.mjs from the validated Observatory Navigator binding. */\nwindow.NEXAH_OBSERVATORY_BINDING = ${serialized};\n`;

fs.writeFileSync(target, output);
console.log(JSON.stringify({
  status: "PASS",
  source: path.basename(source),
  target: path.relative(here, target),
  typed_fields: binding.typed_fields.length,
  family_bindings: binding.family_bindings.length,
  highlights: binding.highlights.length,
  bytes: Buffer.byteLength(output)
}, null, 2));
